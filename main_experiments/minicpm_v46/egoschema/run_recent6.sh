#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
PYTHON_BIN="${PYTHON_BIN:-$(command -v python || command -v python3)}"
NUM_PROCESSES="${NUM_PROCESSES:-8}"
MAIN_PROCESS_PORT="${MAIN_PROCESS_PORT:-29962}"
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION:-sdpa}"
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE:-16x}"
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS:-1}"
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS:-1}"
MINICPM_QA_DEVICE="${MINICPM_QA_DEVICE:-}"
MINICPM_QA_MODEL="${MINICPM_QA_MODEL:-openbmb/MiniCPM-V-4.6}"
MINICPM_LOAD_ON_CPU_FIRST="${MINICPM_LOAD_ON_CPU_FIRST:-0}"
HF_ENABLE_PARALLEL_LOADING="${HF_ENABLE_PARALLEL_LOADING:-false}"
HF_PARALLEL_LOADING_WORKERS="${HF_PARALLEL_LOADING_WORKERS:-1}"
HF_DEACTIVATE_ASYNC_LOAD="${HF_DEACTIVATE_ASYNC_LOAD:-1}"
MINICPM_SERIALIZE_MODEL_LOAD="${MINICPM_SERIALIZE_MODEL_LOAD:-1}"
MINICPM_MODEL_LOAD_TIMEOUT="${MINICPM_MODEL_LOAD_TIMEOUT:-7200}"
MINICPM_SEED="${MINICPM_SEED:-42}"
QWEN_EXACT_RECENT_DECODE="${QWEN_EXACT_RECENT_DECODE:-1}"

EGOSCHEMA_DATASET_PATH="${EGOSCHEMA_DATASET_PATH:-lmms-lab/egoschema}"
EGOSCHEMA_DATASET_NAME="${EGOSCHEMA_DATASET_NAME:-Subset}"
EGOSCHEMA_SPLIT="${EGOSCHEMA_SPLIT:-test}"
EGOSCHEMA_ANNOTATION_JSON="${EGOSCHEMA_ANNOTATION_JSON:-}"
EGOSCHEMA_VIDEO_DIR="${EGOSCHEMA_VIDEO_DIR:-}"
EGOSCHEMA_RESULT_DIR="${EGOSCHEMA_RESULT_DIR:-${REPO_ROOT}/main_experiments/results/repro_egoschema/egoschema_subset_minicpmv46_recent6_d8}"
EGOSCHEMA_MAX_SAMPLES="${EGOSCHEMA_MAX_SAMPLES:-${MAX_SAMPLES:-}}"

cd "${REPO_ROOT}"
if [[ -z "${CUDA_VISIBLE_DEVICES:-}" ]]; then
    CUDA_VISIBLE_DEVICES="0,1,2,3,4,5,6,7"
fi

echo "[INFO] Using PYTHON_BIN=${PYTHON_BIN}"
echo "[INFO] Using CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES}"
echo "[INFO] Using NUM_PROCESSES=${NUM_PROCESSES}"
echo "[INFO] Using MINICPM_SEED=${MINICPM_SEED}"
echo "[INFO] Using MINICPM_QA_MODEL=${MINICPM_QA_MODEL}"
echo "[INFO] Using QWEN_EXACT_RECENT_DECODE=${QWEN_EXACT_RECENT_DECODE}"
echo "[INFO] Using EgoSchema ${EGOSCHEMA_DATASET_PATH}/${EGOSCHEMA_DATASET_NAME}/${EGOSCHEMA_SPLIT}"
echo "[INFO] Using EGOSCHEMA_ANNOTATION_JSON=${EGOSCHEMA_ANNOTATION_JSON:-<huggingface dataset>}"
echo "[INFO] Using EGOSCHEMA_VIDEO_DIR=${EGOSCHEMA_VIDEO_DIR:-<HF_HOME/hub/egoschema/videos>}"
echo "[INFO] Results: ${EGOSCHEMA_RESULT_DIR}"

COMMON_ARGS=(
    --dataset-path "${EGOSCHEMA_DATASET_PATH}" \
    --dataset-name "${EGOSCHEMA_DATASET_NAME}" \
    --split "${EGOSCHEMA_SPLIT}" \
    --output-dir "${EGOSCHEMA_RESULT_DIR}" \
    --mode recent6 \
    --qa-model "${MINICPM_QA_MODEL}" \
    --recent-frames-only 6 \
    --chunk-duration 1.0 \
    --fps 1.0 \
    --max-qa-tokens 256
)
if [[ -n "${EGOSCHEMA_VIDEO_DIR}" ]]; then
    COMMON_ARGS+=(--video-dir "${EGOSCHEMA_VIDEO_DIR}")
fi
if [[ -n "${EGOSCHEMA_ANNOTATION_JSON}" ]]; then
    COMMON_ARGS+=(--annotation-json "${EGOSCHEMA_ANNOTATION_JSON}")
fi
if [[ -n "${MINICPM_QA_DEVICE}" ]]; then
    COMMON_ARGS+=(--qa-device "${MINICPM_QA_DEVICE}")
fi
if [[ -n "${EGOSCHEMA_MAX_SAMPLES}" ]]; then
    COMMON_ARGS+=(--max-samples "${EGOSCHEMA_MAX_SAMPLES}")
fi

CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES}" \
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION}" \
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE}" \
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS}" \
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS}" \
MINICPM_LOAD_ON_CPU_FIRST="${MINICPM_LOAD_ON_CPU_FIRST}" \
HF_ENABLE_PARALLEL_LOADING="${HF_ENABLE_PARALLEL_LOADING}" \
HF_PARALLEL_LOADING_WORKERS="${HF_PARALLEL_LOADING_WORKERS}" \
HF_DEACTIVATE_ASYNC_LOAD="${HF_DEACTIVATE_ASYNC_LOAD}" \
MINICPM_SERIALIZE_MODEL_LOAD="${MINICPM_SERIALIZE_MODEL_LOAD}" \
MINICPM_MODEL_LOAD_TIMEOUT="${MINICPM_MODEL_LOAD_TIMEOUT}" \
MINICPM_SEED="${MINICPM_SEED}" \
QWEN_EXACT_RECENT_DECODE="${QWEN_EXACT_RECENT_DECODE}" \
PYTHONHASHSEED="${MINICPM_SEED}" \
"${PYTHON_BIN}" -m accelerate.commands.launch \
    --num_processes "${NUM_PROCESSES}" \
    --main_process_port "${MAIN_PROCESS_PORT}" \
    --multi_gpu \
    --mixed_precision bf16 \
    main_experiments/minicpm_v46/egoschema/eval_egoschema_dist.py "${COMMON_ARGS[@]}"
