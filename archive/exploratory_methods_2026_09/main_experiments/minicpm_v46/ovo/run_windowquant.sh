#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
PYTHON_BIN="${PYTHON_BIN:-$(command -v python || command -v python3)}"
NUM_PROCESSES="${NUM_PROCESSES:-8}"
MAIN_PROCESS_PORT="${MAIN_PROCESS_PORT:-29941}"
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION:-sdpa}"
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE:-16x}"
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS:-1}"
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS:-1}"
RECENT_FRAMES_ONLY="${RECENT_FRAMES_ONLY:-6}"
MAX_SAMPLES_PER_SPLIT="${MAX_SAMPLES_PER_SPLIT:-}"

MINICPM_WINDOWQUANT_WINDOW_SIZE="${MINICPM_WINDOWQUANT_WINDOW_SIZE:-16}"
MINICPM_WINDOWQUANT_LOW_BITS="${MINICPM_WINDOWQUANT_LOW_BITS:-4}"
MINICPM_WINDOWQUANT_HIGH_BITS="${MINICPM_WINDOWQUANT_HIGH_BITS:-8}"
MINICPM_WINDOWQUANT_HIGH_RATIO="${MINICPM_WINDOWQUANT_HIGH_RATIO:-0.25}"
MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS="${MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS:-1}"

OVO_ANNO_PATH="${REPO_ROOT}/data/ovo_bench/ovo_bench_new.json"
OVO_CHUNKED_DIR="${REPO_ROOT}/data/ovo_bench/chunked_videos"
OVO_RESULT_DIR="${OVO_RESULT_DIR:-${REPO_ROOT}/main_experiments/results/repro_windowquant/ovo_minicpmv46_windowquant_recent${RECENT_FRAMES_ONLY}_w${MINICPM_WINDOWQUANT_WINDOW_SIZE}_${MINICPM_WINDOWQUANT_LOW_BITS}-${MINICPM_WINDOWQUANT_HIGH_BITS}b_d8}"

cd "${REPO_ROOT}"

echo "[INFO] Using PYTHON_BIN=${PYTHON_BIN}"
echo "[INFO] Using NUM_PROCESSES=${NUM_PROCESSES}"
echo "[INFO] Using RECENT_FRAMES_ONLY=${RECENT_FRAMES_ONLY}"
echo "[INFO] WindowQuant window=${MINICPM_WINDOWQUANT_WINDOW_SIZE}, bits=${MINICPM_WINDOWQUANT_LOW_BITS}/${MINICPM_WINDOWQUANT_HIGH_BITS}, high_ratio=${MINICPM_WINDOWQUANT_HIGH_RATIO}, protect_recent=${MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS}"
echo "[INFO] Results: ${OVO_RESULT_DIR}"

COMMON_ARGS=(
    --model_path "openbmb/MiniCPM-V-4.6" \
    --anno_path "${OVO_ANNO_PATH}" \
    --chunked_dir "${OVO_CHUNKED_DIR}" \
    --result_dir "${OVO_RESULT_DIR}" \
    --recent_frames_only "${RECENT_FRAMES_ONLY}" \
    --chunk_duration 1.0 \
    --fps 1.0 \
    --max_qa_tokens 256 \
    --wq-window-size "${MINICPM_WINDOWQUANT_WINDOW_SIZE}" \
    --wq-low-bits "${MINICPM_WINDOWQUANT_LOW_BITS}" \
    --wq-high-bits "${MINICPM_WINDOWQUANT_HIGH_BITS}" \
    --wq-high-ratio "${MINICPM_WINDOWQUANT_HIGH_RATIO}" \
    --wq-protect-recent-windows "${MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS}"
)

if [[ -n "${MAX_SAMPLES_PER_SPLIT}" ]]; then
    COMMON_ARGS+=(--max_samples_per_split "${MAX_SAMPLES_PER_SPLIT}")
fi

CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}" \
HIP_VISIBLE_DEVICES="${HIP_VISIBLE_DEVICES:-0,1,2,3,4,5,6,7}" \
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION}" \
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE}" \
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS}" \
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS}" \
MINICPM_WINDOWQUANT_WINDOW_SIZE="${MINICPM_WINDOWQUANT_WINDOW_SIZE}" \
MINICPM_WINDOWQUANT_LOW_BITS="${MINICPM_WINDOWQUANT_LOW_BITS}" \
MINICPM_WINDOWQUANT_HIGH_BITS="${MINICPM_WINDOWQUANT_HIGH_BITS}" \
MINICPM_WINDOWQUANT_HIGH_RATIO="${MINICPM_WINDOWQUANT_HIGH_RATIO}" \
MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS="${MINICPM_WINDOWQUANT_PROTECT_RECENT_WINDOWS}" \
"${PYTHON_BIN}" -m accelerate.commands.launch \
    --num_processes "${NUM_PROCESSES}" \
    --main_process_port "${MAIN_PROCESS_PORT}" \
    --multi_gpu \
    --mixed_precision bf16 \
    main_experiments/minicpm_v46/ovo/eval_windowquant.py "${COMMON_ARGS[@]}"
