#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/../../.." && pwd)"
PYTHON_BIN="${PYTHON_BIN:-$(command -v python || command -v python3)}"
NUM_PROCESSES="${NUM_PROCESSES:-8}"
MAIN_PROCESS_PORT="${MAIN_PROCESS_PORT:-29881}"
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION:-sdpa}"
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE:-16x}"
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS:-1}"
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS:-1}"
MINICPM_QA_DEVICE="${MINICPM_QA_DEVICE:-}"
MINICPM_LOAD_ON_CPU_FIRST="${MINICPM_LOAD_ON_CPU_FIRST:-0}"
HF_ENABLE_PARALLEL_LOADING="${HF_ENABLE_PARALLEL_LOADING:-false}"
HF_PARALLEL_LOADING_WORKERS="${HF_PARALLEL_LOADING_WORKERS:-1}"
HF_DEACTIVATE_ASYNC_LOAD="${HF_DEACTIVATE_ASYNC_LOAD:-1}"
MINICPM_SERIALIZE_MODEL_LOAD="${MINICPM_SERIALIZE_MODEL_LOAD:-1}"
MINICPM_MODEL_LOAD_TIMEOUT="${MINICPM_MODEL_LOAD_TIMEOUT:-7200}"
RSM_RECENT_FRAMES="${RSM_RECENT_FRAMES:-6}"
RSM_UPDATE_BATCH="${RSM_UPDATE_BATCH:-4}"
RSM_MAX_STORY_TOKENS="${RSM_MAX_STORY_TOKENS:-256}"
RSM_REWRITE_MAX_NEW_TOKENS="${RSM_REWRITE_MAX_NEW_TOKENS:-384}"
RSM_COMPRESS_MAX_NEW_TOKENS="${RSM_COMPRESS_MAX_NEW_TOKENS:-320}"
RSM_MAX_COMPRESSION_ATTEMPTS="${RSM_MAX_COMPRESSION_ATTEMPTS:-1}"
RSM_PROMPT_TAG="${RSM_PROMPT_TAG:-v1}"
RSM_CONTEXT_TIME="${RSM_CONTEXT_TIME:--1}"
MAX_SAMPLES="${MAX_SAMPLES:-}"

SB_ANNO_PATH="${REPO_ROOT}/data/streamingbench/questions_real.json"
SB_VIDEO_DIR="${REPO_ROOT}/data/streamingbench/videos"
SB_RESULT_DIR="${SB_RESULT_DIR:-${REPO_ROOT}/main_experiments/results/repro_recursive_story_memory/streamingbench_minicpmv46_recursive_story_memory_recent${RSM_RECENT_FRAMES}_b${RSM_UPDATE_BATCH}_l${RSM_MAX_STORY_TOKENS}_${RSM_PROMPT_TAG}_d8}"

cd "${REPO_ROOT}"
if [[ -z "${CUDA_VISIBLE_DEVICES:-}" ]]; then
    CUDA_VISIBLE_DEVICES="0,1,2,3,4,5,6,7"
fi

echo "[INFO] Using PYTHON_BIN=${PYTHON_BIN}"
echo "[INFO] Using CUDA_VISIBLE_DEVICES=${CUDA_VISIBLE_DEVICES}"
echo "[INFO] Using NUM_PROCESSES=${NUM_PROCESSES}"
echo "[INFO] Using RSM_RECENT_FRAMES=${RSM_RECENT_FRAMES}"
echo "[INFO] Using RSM_UPDATE_BATCH=${RSM_UPDATE_BATCH}"
echo "[INFO] Using RSM_MAX_STORY_TOKENS=${RSM_MAX_STORY_TOKENS}"
echo "[INFO] Using RSM_REWRITE_MAX_NEW_TOKENS=${RSM_REWRITE_MAX_NEW_TOKENS}"
echo "[INFO] Using RSM_COMPRESS_MAX_NEW_TOKENS=${RSM_COMPRESS_MAX_NEW_TOKENS}"
echo "[INFO] Using RSM_MAX_COMPRESSION_ATTEMPTS=${RSM_MAX_COMPRESSION_ATTEMPTS}"
echo "[INFO] Using RSM_PROMPT_TAG=${RSM_PROMPT_TAG}"
echo "[INFO] Using RSM_CONTEXT_TIME=${RSM_CONTEXT_TIME}"
echo "[INFO] Results: ${SB_RESULT_DIR}"

COMMON_ARGS=(
    --anno-path "${SB_ANNO_PATH}" \
    --video-dir "${SB_VIDEO_DIR}" \
    --qa-model "openbmb/MiniCPM-V-4.6" \
    --top-k 0 \
    --recent-frames-only "${RSM_RECENT_FRAMES}" \
    --chunk-duration 1.0 \
    --fps 1.0 \
    --context-time "${RSM_CONTEXT_TIME}" \
    --max-qa-tokens 256 \
    --output-dir "${SB_RESULT_DIR}" \
    --rsm-recent-frames "${RSM_RECENT_FRAMES}" \
    --rsm-update-batch "${RSM_UPDATE_BATCH}" \
    --rsm-max-story-tokens "${RSM_MAX_STORY_TOKENS}" \
    --rsm-rewrite-max-new-tokens "${RSM_REWRITE_MAX_NEW_TOKENS}" \
    --rsm-compress-max-new-tokens "${RSM_COMPRESS_MAX_NEW_TOKENS}" \
    --rsm-max-compression-attempts "${RSM_MAX_COMPRESSION_ATTEMPTS}"
)
if [[ -n "${MINICPM_QA_DEVICE}" ]]; then
    COMMON_ARGS+=(--qa-device "${MINICPM_QA_DEVICE}")
fi
if [[ -n "${MAX_SAMPLES}" ]]; then
    COMMON_ARGS+=(--max-samples "${MAX_SAMPLES}")
fi

CUDA_VISIBLE_DEVICES="${CUDA_VISIBLE_DEVICES}" \
ATTN_IMPLEMENTATION="${ATTN_IMPLEMENTATION}" \
MINICPM_DOWNSAMPLE_MODE="${MINICPM_DOWNSAMPLE_MODE}" \
MINICPM_MAX_SLICE_NUMS="${MINICPM_MAX_SLICE_NUMS}" \
MINICPM_PROFILE_COMPONENTS="${MINICPM_PROFILE_COMPONENTS}" \
MINICPM_LOAD_ON_CPU_FIRST="${MINICPM_LOAD_ON_CPU_FIRST}" \
HF_ENABLE_PARALLEL_LOADING="${HF_ENABLE_PARALLEL_LOADING}" \
HF_PARALLEL_LOADING_WORKERS="${HF_PARALLEL_LOADING_WORKERS}" \
HF_DEACTIVATE_ASYNC_LOAD="${HF_DEACTIVATE_ASYNC_LOAD}" \
MINICPM_SERIALIZE_MODEL_LOAD="${MINICPM_SERIALIZE_MODEL_LOAD}" \
MINICPM_MODEL_LOAD_TIMEOUT="${MINICPM_MODEL_LOAD_TIMEOUT}" \
MINICPM_RSM_RECENT_FRAMES="${RSM_RECENT_FRAMES}" \
MINICPM_RSM_UPDATE_BATCH="${RSM_UPDATE_BATCH}" \
MINICPM_RSM_MAX_STORY_TOKENS="${RSM_MAX_STORY_TOKENS}" \
MINICPM_RSM_REWRITE_MAX_NEW_TOKENS="${RSM_REWRITE_MAX_NEW_TOKENS}" \
MINICPM_RSM_COMPRESS_MAX_NEW_TOKENS="${RSM_COMPRESS_MAX_NEW_TOKENS}" \
MINICPM_RSM_MAX_COMPRESSION_ATTEMPTS="${RSM_MAX_COMPRESSION_ATTEMPTS}" \
MINICPM_RSM_PROMPT_VERSION="${RSM_PROMPT_TAG}" \
"${PYTHON_BIN}" -m accelerate.commands.launch \
    --num_processes "${NUM_PROCESSES}" \
    --main_process_port "${MAIN_PROCESS_PORT}" \
    --multi_gpu \
    --mixed_precision bf16 \
    main_experiments/minicpm_v46/streamingbench/eval_recursive_story_memory_dist.py "${COMMON_ARGS[@]}"
